function stubOps(opts?: { onPrompt?: (input: SessionPrompt.PromptInput) => void; text?: string }): TaskPromptOps {
  return {
    cancel: () => Effect.void,
    resolvePromptParts: (template) => Effect.succeed([{ type: "text" as const, text: template }]),
    prompt: (input) =>
      Effect.sync(() => {
        opts?.onPrompt?.(input)
        return reply(input, opts?.text ?? "done")
      }),
  }
}

function reply(input: SessionPrompt.PromptInput, text: string): SessionV1.WithParts {
  const id = MessageID.ascending()
  return {
    info: {
      id,
      role: "assistant",
      parentID: input.messageID ?? MessageID.ascending(),
      sessionID: input.sessionID,
      mode: input.agent ?? "general",
      agent: input.agent ?? "general",
      cost: 0,
      path: { cwd: "/tmp", root: "/tmp" },
      tokens: { input: 0, output: 0, reasoning: 0, cache: { read: 0, write: 0 } },
      modelID: input.model?.modelID ?? ref.modelID,
      providerID: input.model?.providerID ?? ref.providerID,
      time: { created: Date.now() },
      finish: "stop",
    },
    parts: [
      {
        id: PartID.ascending(),
        messageID: id,
        sessionID: input.sessionID,
        type: "text",
        text,
      },
    ],
  }
}

function assistantResult(
  input: SessionPrompt.PromptInput,
  opts: {
    texts?: string[]
    reasoning?: string[]
    finish?: SessionV1.Assistant["finish"]
    error?: SessionV1.Assistant["error"]
    tokens?: Partial<SessionV1.Assistant["tokens"]>
  } = {},
): SessionV1.WithParts {
  const result = reply(input, "")
  if (result.info.role !== "assistant") throw new Error("expected assistant result")
  result.info.finish = opts.finish ?? "stop"
  result.info.error = opts.error
  result.info.tokens = {
    ...result.info.tokens,
    ...opts.tokens,
    cache: {
      ...result.info.tokens.cache,
      ...opts.tokens?.cache,
    },
  }
  result.parts = [
    ...(opts.reasoning ?? []).map(
      (text) =>
        ({
          id: PartID.ascending(),
          messageID: result.info.id,
          sessionID: input.sessionID,
          type: "reasoning",
          text,
          time: { start: Date.now(), end: Date.now() },
        }) satisfies SessionV1.ReasoningPart,
    ),
    ...(opts.texts ?? []).map(
      (text) =>
        ({
          id: PartID.ascending(),
          messageID: result.info.id,
          sessionID: input.sessionID,
          type: "text",
          text,
        }) satisfies SessionV1.TextPart,
    ),
  ]
  return result
}

function exitError<A, E>(exit: Exit.Exit<A, E>) {
  if (Exit.isSuccess(exit)) return undefined
  const error = Cause.squash(exit.cause)
  return error instanceof Error ? error.message : String(error)
}

function escapeTaskText(value: string) {
  return value
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&apos;")
}

