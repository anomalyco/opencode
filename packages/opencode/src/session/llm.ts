  async function hookPart(input: {
    sessionID: string
    messageID: string
    plugin: string
    hook: string
    stage: "before" | "after" | "error"
    error?: string
  }) {
    const now = Date.now()
    await Session.updatePart({
      id: Identifier.ascending("part"),
      messageID: input.messageID,
      sessionID: input.sessionID,
      type: "tool",
      callID: ulid(),
      tool: "hook",
      state: {
        status: "completed",
        input: {
          hook: input.plugin,
          hook_type: `${input.stage} ${input.hook}`,
          event: input.hook,
        },
        output: input.error ?? "",
        title: input.plugin,
        metadata: {
          hook: input.plugin,
          hook_type: `${input.stage} ${input.hook}`,
          event: input.hook,
          output: input.error ?? "",
        },
        time: {
          start: now,
          end: now,
        },
      },
      metadata: {
        hook: input.plugin,
        hook_type: `${input.stage} ${input.hook}`,
        event: input.hook,
        error: input.error,
      },
    })
  }

  function hookOpts(sessionID: string, messageID: string) {
    return {
      onInvoke: async (event: {
        plugin: string
        custom: boolean
        hook: string
        stage: "before" | "after" | "error"
        error?: string
      }) => {
        if (!event.custom) return
        try {
          await hookPart({
            sessionID,
            messageID,
            plugin: event.plugin,
            hook: event.hook,
            stage: event.stage,
            error: event.error,
          })
        } catch (err) {
          log.debug("skip hook timeline part", {
            sessionID,
            messageID,
            plugin: event.plugin,
            hook: event.hook,
            stage: event.stage,
            error: err instanceof Error ? err.message : String(err),
          })
        }
      },
    }
  }

