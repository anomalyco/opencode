export type SpinnerStyle = keyof typeof SPINNER_STYLES

export function Spinner(props: {
  children?: JSX.Element
  color?: RGBA
  style?: SpinnerStyle
  interval?: number
}) {
  const { theme } = useTheme()
  const kv = useKV()
  const color = () => props.color ?? theme.primary
  const style = () => props.style ?? (kv.get("spinner_style", "dots") as SpinnerStyle)
  const interval = () => props.interval ?? kv.get("spinner_interval", 80)
  const frames = createMemo(() => SPINNER_STYLES[style()] ?? SPINNER_STYLES.dots)

  return (
    <Show when={kv.get("animations_enabled", true)} fallback={<text fg={color()}>⋯ {props.children}</text>}>
      <box flexDirection="row" gap={1}>
        <spinner frames={[...frames()]} interval={interval()} color={color()} />
        <Show when={props.children}>
          <text fg={color()}>{props.children}</text>
        </Show>
      </box>
    </Show>
  )
}
