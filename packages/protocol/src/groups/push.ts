import { Schema } from "effect"
import { HttpApiEndpoint, HttpApiGroup, HttpApiSchema, OpenApi } from "effect/http-api"
import { ForbiddenError, InvalidRequestError, ServiceUnavailableError } from "../errors.js"

export const PushSubscriptionID = Schema.String.check(Schema.isUUID()).annotate({
  identifier: "Push.SubscriptionID",
})

export const PushCategory = Schema.Literals(["agent", "permissions", "questions", "errors"]).annotate({
  identifier: "Push.Category",
})
export type PushCategory = typeof PushCategory.Type

const Title = Schema.String.check(Schema.isMinLength(1), Schema.isMaxLength(100))

export const PushPreferences = Schema.Struct({
  agent: Schema.Boolean,
  permissions: Schema.Boolean,
  questions: Schema.Boolean,
  errors: Schema.Boolean,
}).annotate({ identifier: "Push.Preferences" })
export interface PushPreferences extends Schema.Schema.Type<typeof PushPreferences> {}

// The browser gives no access to the app's i18n catalogue from a service worker, so each
// subscription carries the titles its owner chose when it registered.
export const PushTitles = Schema.Struct({
  agent: Title,
  permissions: Title,
  questions: Title,
  errors: Title,
}).annotate({ identifier: "Push.Titles" })
export interface PushTitles extends Schema.Schema.Type<typeof PushTitles> {}

export const PushSubscription = Schema.Struct({
  id: PushSubscriptionID,
  endpoint: Schema.String.check(Schema.isMinLength(1), Schema.isMaxLength(2048)),
  keys: Schema.Struct({
    p256dh: Schema.String.check(Schema.isPattern(/^[A-Za-z0-9_-]{87}$/)),
    auth: Schema.String.check(Schema.isPattern(/^[A-Za-z0-9_-]{22}$/)),
  }),
  // The app route prefix that notification clicks reopen, for example
  // https://example.com/server/<key>/session/. The server appends the session ID.
  url: Schema.String.check(Schema.isMinLength(1), Schema.isMaxLength(1024)),
  preferences: PushPreferences,
  titles: PushTitles,
}).annotate({ identifier: "Push.Subscription" })
export type PushSubscription = typeof PushSubscription.Type

export const PushKey = Schema.Struct({ publicKey: Schema.String }).annotate({ identifier: "Push.Key" })
export type PushKey = typeof PushKey.Type

export const PushGroup = HttpApiGroup.make("server.push")
  .add(
    HttpApiEndpoint.get("push.get", "/api/push", {
      success: PushKey,
      error: ServiceUnavailableError,
    }).annotateMerge(
      OpenApi.annotations({
        identifier: "push.get",
        summary: "Get the Web Push public key",
        description: "Return the VAPID public key this server signs push messages with.",
      }),
    ),
  )
  .add(
    HttpApiEndpoint.put("push.subscribe", "/api/push/subscription", {
      payload: PushSubscription,
      success: PushSubscriptionID,
      error: [InvalidRequestError, ForbiddenError, ServiceUnavailableError],
    }).annotateMerge(
      OpenApi.annotations({
        identifier: "push.subscribe",
        summary: "Register a browser push subscription",
        description:
          "Register or refresh this browser installation. The subscription id is generated by the browser and reused until the device disables push.",
      }),
    ),
  )
  .add(
    HttpApiEndpoint.delete("push.unsubscribe", "/api/push/subscription/:id", {
      params: { id: PushSubscriptionID },
      success: HttpApiSchema.NoContent,
      error: [ForbiddenError, ServiceUnavailableError],
    }).annotateMerge(
      OpenApi.annotations({
        identifier: "push.unsubscribe",
        summary: "Remove a browser push subscription",
        description: "Stop sending notifications to one browser installation.",
      }),
    ),
  )
  .annotateMerge(OpenApi.annotations({ title: "push", description: "Self-hosted Web Push subscriptions." }))
