#!/usr/bin/env bun

// Embeds the canonical `.js` sources as strings, so they import as plain TypeScript (tsc has no text loader).

import path from "node:path"
import { format, resolveConfig } from "prettier"

const src = path.resolve(import.meta.dir, "../src")
const names = [
  "prelude",
  "templates/suggestions",
  "templates/form",
  "templates/confirm",
  "templates/chart",
  "templates/backdrop",
  "templates/minigame",
  ...[
    "pie",
    "scatter",
    "histogram",
    "area",
    "heatmap",
    "treemap",
    "sankey",
    "graph",
    "tree",
    "timeline",
    "funnel",
    "radar",
    "gauge",
    "boxplot",
    "flowchart",
    "sequence",
    "table",
  ].map((name) => `templates/${name}`),
]
const sources = await Promise.all(names.map((name) => Bun.file(path.join(src, `${name}.js`)).text()))

const file = path.join(src, "source.ts")
const text = [
  "// Generated by script/generate.ts from prelude.js and templates/*.js. Do not edit; run `bun run generate`.",
  "",
  ...names.map((name, index) => `export const ${path.basename(name)} = ${JSON.stringify(sources[index])}`),
  "",
].join("\n")

await Bun.write(file, await format(text, { ...(await resolveConfig(file)), filepath: file }))
