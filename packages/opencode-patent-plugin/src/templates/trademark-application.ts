/**
 * 商标注册申请书结构模板
 */
export function trademarkApplicationTemplate(): string {
  return `# 商标注册申请书

## 一、申请人信息

- 申请人名称（中文）：[名称]
- 申请人名称（英文）：[Name]
- 地址（中文）：[地址]
- 国籍/地区：[国籍]
- 统一社会信用代码/身份证号：[编号]

## 二、商标信息

- 商标名称：[商标名称]
- 商标类型：[文字/图形/组合/立体/颜色/声音]
- 商标说明：[商标含义、设计理念等说明]

## 三、商品/服务项目

### 第[N]类

| 序号 | 商品/服务名称 | 类似群 |
|------|-------------|--------|
| 1 | [商品/服务] | [类似群号] |

## 四、优先权（如有）

- 优先权日：[日期]
- 优先权号：[编号]
- 优先权国：[国家]

---
*本申请书为草案，需经专业审校后提交。*`
}

/**
 * 商标说明模板（按类型区分）
 */
export function trademarkDescriptionTemplate(type: string): string {
  const templates: Record<string, string> = {
    "文字": `## 商标说明

本商标为文字商标，由"[文字内容]"构成。

**字体**：[字体描述，如：宋体/楷体/常规字体]
**含义**：[商标文字的含义或由来]
**是否为外文**：[是/否，如为外文请说明翻译]

**显著性说明**：该商标非本商品/服务的通用名称、图形或型号，具有显著性。`,

    "图形": `## 商标说明

本商标为图形商标，由[描述图形要素]构成。

**图形要素描述**：
- [描述图形的主要构成要素]
- [描述颜色（如有）]
- [描述整体构图特点]

**设计理念**：[说明图形的设计含义]

**显著性说明**：该图形非本商品/服务的通用图形，具有显著性。`,

    "组合": `## 商标说明

本商标为组合商标，由文字"[文字内容]"和图形要素组合构成。

**文字部分**：[文字内容及字体]
**图形部分**：[图形描述]
**组合方式**：[描述文字与图形的位置关系]
**整体含义**：[说明商标整体含义]

**显著性说明**：该组合商标各要素协同表达特定含义，具有整体显著性。`,

    "立体": `## 商标说明

本商标为立体商标，为[商品/包装]的三维形状。

**立体形状描述**：[详细描述三维形状特征]
**视图说明**：[说明提交的各角度视图]

**显著性说明**：该立体形状非商品自身性质产生的形状，也非获得技术效果所需形状，具有显著性。`,

    "颜色": `## 商标说明

本商标为颜色组合商标，由[颜色1]和[颜色2]组合构成。

**颜色组合描述**：[描述颜色的具体色值和组合方式]
**使用方式**：[说明颜色组合在商品/服务上的使用方式]

**显著性说明**：该颜色组合非商品/行业的通用颜色，通过长期使用已获得显著性。`,

    "声音": `## 商标说明

本商标为声音商标，为[描述声音特征]。

**声音描述**：[描述旋律、节奏、音色等]
**五线谱/文字描述**：[附五线谱或详细文字描述]

**显著性说明**：该声音非商品/行业的通用声音，具有显著识别性。`,
  }

  return templates[type] || templates["文字"]
}
