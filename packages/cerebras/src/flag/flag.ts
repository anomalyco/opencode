  export const CEREBRAS_EXPERIMENTAL_WATCHER = CEREBRAS_EXPERIMENTAL || truthy("CEREBRAS_EXPERIMENTAL_WATCHER")

  function truthy(key: string) {
    const value = process.env[key]?.toLowerCase()
    return value === "true" || value === "1"
  }
