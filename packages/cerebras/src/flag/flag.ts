  export const CEREBRAS_CONFIG = process.env["CEREBRAS_CONFIG"]
  export const CEREBRAS_CONFIG_DIR = process.env["CEREBRAS_CONFIG_DIR"]
  export const CEREBRAS_CONFIG_CONTENT = process.env["CEREBRAS_CONFIG_CONTENT"]
  export const CEREBRAS_DISABLE_AUTOUPDATE = truthy("CEREBRAS_DISABLE_AUTOUPDATE")
  export const CEREBRAS_DISABLE_PRUNE = truthy("CEREBRAS_DISABLE_PRUNE")
  export const CEREBRAS_PERMISSION = process.env["CEREBRAS_PERMISSION"]
  export const CEREBRAS_DISABLE_DEFAULT_PLUGINS = truthy("CEREBRAS_DISABLE_DEFAULT_PLUGINS")
  export const CEREBRAS_DISABLE_LSP_DOWNLOAD = truthy("CEREBRAS_DISABLE_LSP_DOWNLOAD")
