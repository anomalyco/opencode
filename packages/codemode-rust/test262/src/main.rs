//! Runs the reference's pinned test262 file set through PsychoScript with the reference harness semantics
//! (`packages/codemode/test/test262/run.ts`) and checks the outcome in both directions: against
//! `test262/rust-skipped.txt` (gaps here) and `test262/reference-gaps.txt` (gaps in the reference).
//!
//! Usage: psychoscript-test262 --root DIR --reference-skipped FILE --skipped FILE --reference-gaps FILE
//!        [--write] [--jobs N] [prefix]
//!
//! - `--root` is the synced tree holding `built-ins/` and `language/`; see `test262/run.sh`.
//! - A file outside the reference's `skipped.txt` must pass unless `--skipped` lists it, and every listed file must
//!   still fail.
//! - A file in the reference's `skipped.txt` must fail unless `--reference-gaps` lists it, and every listed file must
//!   still pass and still be in the reference's `skipped.txt`. `test262/reference.ts` checks that the reference
//!   still fails them.
//! - `--write` rewrites both lists from the current outcomes instead of checking them. Entries already in
//!   `--reference-gaps` keep their category; new ones are marked uncategorised, with the reference's reason.
//!
//! Each file runs in a worker process, so an abort or a hang in one file is reported as that file's failure.

use std::collections::{BTreeMap, BTreeSet, VecDeque};
use std::io::{BufRead, BufReader, Write};
use std::path::{Path, PathBuf};
use std::process::{Child, ChildStdin, ChildStdout, Command, ExitCode, Stdio};
use std::sync::{Arc, Mutex};
use std::time::{Duration, Instant};

use psychoscript::DiagnosticKind;

/// The reference's per-file limit.
const TIMEOUT_MS: u64 = 5000;
/// A file still running this long after its own timeout is a hang the interpreter cannot interrupt.
const HANG: Duration = Duration::from_secs(30);

const HEADER: &str = "\
test262 files that fail here but pass in the reference: the parity gap list. Generated by
`bash test262/run.sh --write`; CI fails when an unlisted file fails or a listed file passes.
Fix gaps to shrink it; do not add entries.
";

const REFERENCE_HEADER: &str = "\
test262 files the reference skips (its skipped.txt) that pass here: gaps on the TypeScript side. Categories start
with \"real\" (Rust has the behaviour and TypeScript lacks it) or \"accident\" (Rust passes through a looser check,
where the reference is deliberately strict). Generated by `bash test262/run.sh --write`, which keeps the categories;
CI fails when an unlisted file passes, a listed file fails here, or the reference passes a listed file.
";

const PRELUDE: &str = concat!(
    "function assert(mustBeTrue, message) { $assert(mustBeTrue, message) } ",
    "assert.sameValue = $assert.sameValue; assert.notSameValue = $assert.notSameValue; ",
    "assert.compareArray = $assert.compareArray; ",
    "assert.throws = function (expected, func, message) { ",
    "try { func() } catch (thrown) { $assert.thrown(expected, message, thrown); return } ",
    "$assert.notThrown(expected, message) };",
);

fn main() -> ExitCode {
    let args: Vec<String> = std::env::args().skip(1).collect();
    if args.first().map(String::as_str) == Some("--worker") {
        return worker(Path::new(args.get(1).map_or(".", String::as_str)));
    }
    let mut root = None;
    let mut reference_skipped = None;
    let mut skipped = None;
    let mut gaps_path = None;
    let mut write = false;
    let mut jobs = std::thread::available_parallelism().map_or(4, |n| n.get());
    let mut prefix = String::new();
    let mut it = args.into_iter();
    while let Some(arg) = it.next() {
        match arg.as_str() {
            "--root" => root = it.next().map(PathBuf::from),
            "--reference-skipped" => reference_skipped = it.next().map(PathBuf::from),
            "--skipped" => skipped = it.next().map(PathBuf::from),
            "--reference-gaps" => gaps_path = it.next().map(PathBuf::from),
            "--write" => write = true,
            "--jobs" => jobs = it.next().and_then(|n| n.parse().ok()).unwrap_or(jobs),
            p if !p.starts_with("--") => prefix = p.to_owned(),
            other => return usage(&format!("unknown argument {other}")),
        }
    }
    let (Some(root), Some(reference_skipped), Some(skipped), Some(gaps_path)) =
        (root, reference_skipped, skipped, gaps_path)
    else {
        return usage("--root, --reference-skipped, --skipped and --reference-gaps are required");
    };
    if write && !prefix.is_empty() {
        return usage("--write rewrites the whole list, so it takes no prefix");
    }

    let reference = read_list(&reference_skipped);
    let listed = read_list(&skipped);
    let listed_gaps = read_list(&gaps_path);
    let mut files = Vec::new();
    for dir in ["built-ins", "language"] {
        collect(&root, &root.join(dir), &mut files);
    }
    files.sort();
    if files.is_empty() {
        eprintln!(
            "no test262 files under {}; run test262/run.sh",
            root.display()
        );
        return ExitCode::FAILURE;
    }
    let in_scope: BTreeSet<String> = files
        .iter()
        .filter(|f| !reference.contains_key(*f))
        .cloned()
        .collect();
    let queue: VecDeque<String> = files
        .iter()
        .filter(|f| f.starts_with(&prefix))
        .cloned()
        .collect();
    let started = Instant::now();
    let mut results = run_all(&root, queue, jobs.max(1));
    // The reference's own skipped files, checked against `--reference-gaps`.
    let reference_results: BTreeMap<String, Result<(), String>> = results
        .keys()
        .filter(|f| !in_scope.contains(*f))
        .cloned()
        .collect::<Vec<_>>()
        .into_iter()
        .filter_map(|f| results.remove(&f).map(|r| (f, r)))
        .collect();
    let reference_passes: Vec<&String> = reference_results
        .iter()
        .filter(|(_, r)| r.is_ok())
        .map(|(f, _)| f)
        .collect();
    let total = results.len();

    let failures: BTreeMap<&String, &String> = results
        .iter()
        .filter_map(|(f, r)| r.as_ref().err().map(|reason| (f, reason)))
        .collect();
    println!(
        "{} pass, {} fail of {total} files in {:.1} s",
        total - failures.len(),
        failures.len(),
        started.elapsed().as_secs_f64(),
    );
    println!(
        "{} of the {} files in the reference's skipped.txt pass here: gaps on the reference side",
        reference_passes.len(),
        reference_results.len()
    );
    let mut counts: BTreeMap<String, usize> = BTreeMap::new();
    for reason in failures.values() {
        *counts.entry(category(reason)).or_default() += 1;
    }
    let mut counts: Vec<_> = counts.into_iter().collect();
    counts.sort_by(|a, b| b.1.cmp(&a.1).then_with(|| a.0.cmp(&b.0)));
    for (category, count) in &counts {
        println!("{count:>6}  {category}");
    }

    if write {
        let lines: String = HEADER
            .lines()
            .map(|line| format!("# {line}\n").replace("# \n", "#\n"))
            .chain(
                failures
                    .iter()
                    .map(|(file, reason)| format!("{file}  # {}\n", category(reason))),
            )
            .collect();
        if let Err(e) = std::fs::write(&skipped, lines) {
            eprintln!("{}: {e}", skipped.display());
            return ExitCode::FAILURE;
        }
        println!("wrote {} entries to {}", failures.len(), skipped.display());
        let lines: String = REFERENCE_HEADER
            .lines()
            .map(|line| format!("# {line}\n"))
            .chain(reference_passes.iter().map(|file| {
                let category = listed_gaps.get(*file).cloned().unwrap_or_else(|| {
                    let reason = reference.get(*file).map_or("", String::as_str);
                    format!("uncategorised: the reference says {reason}")
                });
                format!("{file}  # {category}\n")
            }))
            .collect();
        if let Err(e) = std::fs::write(&gaps_path, lines) {
            eprintln!("{}: {e}", gaps_path.display());
            return ExitCode::FAILURE;
        }
        println!(
            "wrote {} entries to {}",
            reference_passes.len(),
            gaps_path.display()
        );
        return ExitCode::SUCCESS;
    }

    let new: Vec<_> = failures
        .iter()
        .filter(|(file, _)| !listed.contains_key(**file))
        .collect();
    let fixed: Vec<_> = results
        .iter()
        .filter(|(file, r)| r.is_ok() && listed.contains_key(*file))
        .map(|(file, _)| file)
        .collect();
    let gone: Vec<_> = if prefix.is_empty() {
        listed.keys().filter(|f| !in_scope.contains(*f)).collect()
    } else {
        Vec::new()
    };
    let unlisted_gaps: Vec<_> = reference_passes
        .iter()
        .filter(|f| !listed_gaps.contains_key(**f))
        .collect();
    let failing_gaps: Vec<_> = reference_results
        .iter()
        .filter_map(|(f, r)| match r {
            Err(reason) if listed_gaps.contains_key(f) => Some((f, reason)),
            _ => None,
        })
        .collect();
    let not_skipped: Vec<_> = listed_gaps
        .keys()
        .filter(|f| {
            f.starts_with(&prefix)
                && (!reference.contains_key(*f) || files.binary_search(f).is_err())
        })
        .collect();
    for (file, reason) in &new {
        println!("FAIL  {file}  # {reason}");
    }
    for file in &fixed {
        println!("PASSES NOW, remove it from rust-skipped.txt  {file}");
    }
    for file in &gone {
        println!("NOT IN THE FILE SET, remove it from rust-skipped.txt  {file}");
    }
    for file in &unlisted_gaps {
        println!("PASSES BUT THE REFERENCE SKIPS IT, add it to reference-gaps.txt  {file}");
    }
    for (file, reason) in &failing_gaps {
        println!("FAILS NOW, remove it from reference-gaps.txt  {file}  # {reason}");
    }
    for file in &not_skipped {
        println!("NOT A SKIPPED FILE OF THE REFERENCE, remove it from reference-gaps.txt  {file}");
    }
    let problems = new.len()
        + fixed.len()
        + gone.len()
        + unlisted_gaps.len()
        + failing_gaps.len()
        + not_skipped.len();
    if problems == 0 {
        println!(
            "every failure is listed in {}, and every pass the reference skips in {}",
            skipped.display(),
            gaps_path.display()
        );
        return ExitCode::SUCCESS;
    }
    println!(
        "rust-skipped.txt: {} unlisted failures, {} listed files that pass, {} listed files not in the set",
        new.len(),
        fixed.len(),
        gone.len()
    );
    println!(
        "reference-gaps.txt: {} unlisted passes, {} listed files that fail, {} listed files the reference no longer skips or no longer has",
        unlisted_gaps.len(),
        failing_gaps.len(),
        not_skipped.len()
    );
    ExitCode::FAILURE
}

fn usage(problem: &str) -> ExitCode {
    eprintln!("{problem}");
    eprintln!(
        "usage: psychoscript-test262 --root DIR --reference-skipped FILE --skipped FILE --reference-gaps FILE [--write] [--jobs N] [prefix]"
    );
    ExitCode::FAILURE
}

/// A `path  # reason` list; lines without `#` are ignored, as in the reference.
fn read_list(path: &Path) -> BTreeMap<String, String> {
    std::fs::read_to_string(path)
        .unwrap_or_default()
        .lines()
        .filter(|line| !line.starts_with('#'))
        .filter_map(|line| {
            let (file, reason) = line.split_once('#')?;
            Some((file.trim().to_owned(), reason.trim().to_owned()))
        })
        .collect()
}

fn collect(root: &Path, dir: &Path, out: &mut Vec<String>) {
    let Ok(entries) = std::fs::read_dir(dir) else {
        return;
    };
    for entry in entries.flatten() {
        let path = entry.path();
        if path.is_dir() {
            collect(root, &path, out);
        } else if path.extension().is_some_and(|e| e == "js")
            && let Ok(rel) = path.strip_prefix(root)
        {
            out.push(rel.to_string_lossy().replace('\\', "/"));
        }
    }
}

// ---------- parent: worker pool ----------

type Results = BTreeMap<String, Result<(), String>>;

struct Worker {
    child: Child,
    stdin: ChildStdin,
    stdout: BufReader<ChildStdout>,
}

fn spawn(root: &Path) -> Option<Worker> {
    let exe = std::env::current_exe().ok()?;
    let mut child = Command::new(exe)
        .arg("--worker")
        .arg(root)
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::null())
        .spawn()
        .ok()?;
    let stdin = child.stdin.take()?;
    let stdout = BufReader::new(child.stdout.take()?);
    Some(Worker {
        child,
        stdin,
        stdout,
    })
}

fn run_all(root: &Path, queue: VecDeque<String>, jobs: usize) -> Results {
    let queue = Arc::new(Mutex::new(queue));
    let results = Arc::new(Mutex::new(Results::new()));
    std::thread::scope(|s| {
        for _ in 0..jobs {
            let (queue, results) = (queue.clone(), results.clone());
            s.spawn(move || {
                let mut worker: Option<Worker> = None;
                // A function call, so the queue lock is released before the file runs.
                let next = || queue.lock().ok().and_then(|mut q| q.pop_front());
                while let Some(file) = next() {
                    let outcome = run_in_worker(root, &mut worker, &file);
                    if let Ok(mut r) = results.lock() {
                        r.insert(file, outcome);
                    }
                }
                if let Some(mut w) = worker {
                    drop(w.stdin);
                    let _ = w.child.wait();
                }
            });
        }
    });
    Arc::try_unwrap(results)
        .ok()
        .and_then(|m| m.into_inner().ok())
        .unwrap_or_default()
}

fn run_in_worker(root: &Path, slot: &mut Option<Worker>, file: &str) -> Result<(), String> {
    for _ in 0..2 {
        if slot.is_none() {
            *slot = spawn(root);
        }
        let Some(w) = slot.as_mut() else {
            return Err("crash: cannot start a worker".into());
        };
        if writeln!(w.stdin, "{file}")
            .and_then(|_| w.stdin.flush())
            .is_err()
        {
            if let Some(mut w) = slot.take() {
                let _ = w.child.wait();
            }
            continue;
        }
        let mut line = String::new();
        let read = w.stdout.read_line(&mut line);
        if matches!(read, Ok(n) if n > 0) {
            let line = line.trim_end();
            let (status, reason) = line.split_once('\t').unwrap_or((line, ""));
            if status == "hang"
                && let Some(mut w) = slot.take()
            {
                let _ = w.child.wait();
            }
            return if status == "pass" {
                Ok(())
            } else {
                Err(reason.to_owned())
            };
        }
        let status = slot.take().and_then(|mut w| w.child.wait().ok());
        let how = status.map_or("unknown status".to_owned(), |s| s.to_string());
        return Err(format!("crash: the worker process died ({how})"));
    }
    Err("crash: cannot reach a worker".into())
}

// ---------- worker ----------

fn worker(root: &Path) -> ExitCode {
    let current: Arc<Mutex<Option<Instant>>> = Arc::new(Mutex::new(None));
    let watched = current.clone();
    std::thread::spawn(move || {
        loop {
            std::thread::sleep(Duration::from_millis(500));
            let started = watched.lock().ok().and_then(|c| *c);
            if started.is_some_and(|t| t.elapsed() > HANG + Duration::from_millis(TIMEOUT_MS)) {
                let mut out = std::io::stdout().lock();
                let _ = writeln!(out, "hang\thang: no result after {} s", HANG.as_secs());
                let _ = out.flush();
                std::process::exit(3);
            }
        }
    });
    let stdin = std::io::stdin();
    for line in stdin.lock().lines() {
        let Ok(file) = line else { break };
        if let Ok(mut c) = current.lock() {
            *c = Some(Instant::now());
        }
        let outcome = run_file(&root.join(&file));
        let mut out = std::io::stdout().lock();
        if let Ok(mut c) = current.lock() {
            *c = None;
        }
        let written = match outcome {
            Ok(()) => writeln!(out, "pass"),
            Err(reason) => writeln!(out, "fail\t{}", printable(&reason)),
        };
        if written.and_then(|_| out.flush()).is_err() {
            break;
        }
    }
    ExitCode::SUCCESS
}

/// A reason on one line of printable text.
fn printable(reason: &str) -> String {
    reason
        .chars()
        .map(|c| match c {
            '\n' | '\r' | '\t' => " ".to_owned(),
            c if c.is_control() => c.escape_unicode().to_string(),
            c => c.to_string(),
        })
        .collect()
}

#[derive(Default)]
struct Frontmatter {
    flags: Vec<String>,
    negative: Option<(String, String)>,
}

/// The `flags` and `negative` keys of a test262 YAML frontmatter, in the shapes test262 writes them.
fn frontmatter(source: &str) -> Frontmatter {
    let mut meta = Frontmatter::default();
    let Some(start) = source.find("/*---") else {
        return meta;
    };
    let body = &source[start + 5..];
    let body = &body[..body.find("---*/").unwrap_or(body.len())];
    let mut key = "";
    let (mut phase, mut kind) = (None, None);
    for line in body.lines() {
        let indented = line.starts_with([' ', '\t']);
        let line = line.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        if !indented {
            let (k, v) = line.split_once(':').unwrap_or((line, ""));
            key = k.trim();
            let v = v.trim();
            if key == "flags"
                && let Some(list) = v.strip_prefix('[').and_then(|v| v.strip_suffix(']'))
            {
                meta.flags
                    .extend(list.split(',').map(|f| f.trim().to_owned()));
            }
            continue;
        }
        match key {
            "flags" => {
                if let Some(f) = line.strip_prefix('-') {
                    meta.flags.push(f.trim().to_owned());
                }
            }
            "negative" => {
                if let Some((k, v)) = line.split_once(':') {
                    match k.trim() {
                        "phase" => phase = Some(v.trim().to_owned()),
                        "type" => kind = Some(v.trim().to_owned()),
                        _ => {}
                    }
                }
            }
            _ => {}
        }
    }
    if let (Some(phase), Some(kind)) = (phase, kind) {
        meta.negative = Some((phase, kind));
    }
    meta
}

fn kind_name(kind: &DiagnosticKind) -> &str {
    kind.name()
}

/// One file, with the reference's semantics: strict mode, the prelude on the directive's line, the job queue
/// drained for async tests, and negative tests judged by phase.
fn run_file(path: &Path) -> Result<(), String> {
    let source = std::fs::read_to_string(path).map_err(|e| format!("read: {e}"))?;
    let meta = frontmatter(&source);
    let is_async = meta.flags.iter().any(|f| f == "async");
    let drain = if is_async {
        "\nfor (let i = 0; i < 100; i++) await null"
    } else {
        ""
    };
    let code = format!("\"use strict\"; {PRELUDE}\n{source}{drain}");
    let run = psychoscript::test262::run(&code, TIMEOUT_MS);
    if let Some((phase, kind)) = &meta.negative {
        return match &run.result {
            Ok(()) => Err(format!("expected {kind} but completed")),
            Err(_) if phase == "runtime" => Ok(()),
            Err(d) if d.kind == DiagnosticKind::ParseError => Ok(()),
            Err(d) => Err(format!(
                "expected {kind} but got {}: {}",
                kind_name(&d.kind),
                d.message
            )),
        };
    }
    if let Err(d) = &run.result {
        return Err(format!("{}: {}", kind_name(&d.kind), d.message));
    }
    if !is_async {
        return Ok(());
    }
    match run.done {
        None => Err("$DONE was never called".into()),
        Some(Some(error)) => Err(format!("$DONE: {error}")),
        Some(None) => Ok(()),
    }
}

/// A short, stable reason category for the gap list, from a failure message.
fn category(reason: &str) -> String {
    let unsupported = |r: &str| {
        let r = r.split_once("UnsupportedSyntax: ")?.1;
        Some(format!(
            "unsupported syntax: {}",
            r.split(" is not supported").next()?.to_lowercase()
        ))
    };
    if let Some(c) = unsupported(reason) {
        return c;
    }
    if let Some(rest) = reason.split("Unknown identifier '").nth(1) {
        return format!("missing global: {}", rest.split('\'').next().unwrap_or(""));
    }
    if reason.starts_with("crash:") || reason.starts_with("hang:") {
        return reason.split(" (").next().unwrap_or(reason).to_owned();
    }
    if reason.contains("Internal interpreter error") {
        return "interpreter panic".into();
    }
    if let Some(rest) = reason.strip_prefix("expected ") {
        let kind = rest.split(' ').next().unwrap_or("");
        if rest.ends_with("but completed") {
            return format!("negative test completed: no {kind}");
        }
        let got = rest.split(" but got ").nth(1).unwrap_or("");
        return format!(
            "negative test: {} instead of a parse error",
            got.split(':').next().unwrap_or(got)
        );
    }
    if reason == "$DONE was never called" {
        return "async: $DONE never called".into();
    }
    let (asynchronous, body) = match reason.strip_prefix("$DONE: ") {
        Some(body) => (true, body),
        None => (false, reason),
    };
    let body = body
        .trim_start_matches("ExecutionFailure: ")
        .trim_start_matches("Uncaught: ");
    let category = if let Some((_, rest)) = body.split_once("Expected a ")
        && let Some((expected, rest)) = rest.split_once(" but got a ")
    {
        let actual = rest.split(' ').next().unwrap_or(rest);
        format!("wrong error type: {actual} instead of {expected}")
    } else if let Some((_, rest)) = body.split_once("Expected a ")
        && rest.contains("to be thrown but no exception was thrown")
    {
        format!(
            "error not thrown: {}",
            rest.split(' ').next().unwrap_or(rest)
        )
    } else if body.starts_with("Test262Error") || body.starts_with('"') {
        "wrong result".into()
    } else if let Some(message) = body.strip_prefix("ParseError: ") {
        format!("spurious parse error: {}", normalize(message))
    } else if body.starts_with("TimeoutExceeded") {
        "timeout".into()
    } else if body.contains(" is not a function") {
        "call of a missing method".into()
    } else {
        format!("uncaught {}", normalize(body))
    };
    if asynchronous {
        format!("async: {category}")
    } else {
        category
    }
}

/// Drops what identifies the test rather than the cause: quoted names, numbers and locations.
fn normalize(message: &str) -> String {
    let message = message.trim_start_matches("SyntaxError: ");
    let message = message.split(" (line ").next().unwrap_or(message);
    let mut out = String::new();
    let mut quote = None;
    for c in message.chars() {
        match quote {
            Some(q) if c == q => {
                out.push('…');
                out.push(c);
                quote = None;
            }
            Some(_) => {}
            None if matches!(c, '\'' | '`' | '"') => {
                out.push(c);
                quote = Some(c);
            }
            None if c.is_ascii_digit() => {
                if !out.ends_with('N') {
                    out.push('N');
                }
            }
            None => out.push(c),
        }
    }
    let out = out.trim_end_matches('.').to_owned();
    match out.char_indices().nth(80) {
        Some((i, _)) => format!("{}…", &out[..i]),
        None => out,
    }
}
