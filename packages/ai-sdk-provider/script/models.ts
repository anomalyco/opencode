#!/usr/bin/env bun

import { fileURLToPath } from "node:url"

// Regenerates src/models.ts from OpenCode's public model lists: each chat model's ID and the protocol it's served in
// natively, each Messages model's output limit, and each image model's ID and the images API it's served in. Run before
// a release so new models skip the name guesses in src/index.ts.
const protocols = {
  messages: "messages",
  responses: "responses",
  "generate-content": "google",
  "chat-completions": "chat",
} as const
const imageAPIs = { "/openai/v1": "openai", "/google/v1beta": "google", "/xai/v1": "xai" } as const

type Listed = {
  id: string
  type: string
  limit?: { output?: number }
  api?: Record<string, { base_url?: string }>
  recommended_api?: string
}

const list = (path: string) =>
  fetch(`https://opencode.ai/inference${path}`)
    .then((response) => response.json() as Promise<{ data: Listed[] }>)
    .then((body) => body.data)

const zen = await list("/v1/models")
const go = await list("/go/v1/models")

const chat = [...zen.map((model) => ["", model] as const), ...go.map((model) => ["opencode-go/", model] as const)]
  .filter(([, model]) => model.type === "chat" && model.api !== undefined)
  .flatMap(([prefix, model]) => {
    const api = Object.keys(model.api ?? {})
    const key =
      model.recommended_api !== undefined && model.recommended_api in protocols
        ? model.recommended_api
        : Object.keys(protocols).find((name) => api.includes(name))
    return key === undefined
      ? []
      : [[prefix + model.id, protocols[key as keyof typeof protocols], model.limit?.output] as const]
  })
  .sort(([a], [b]) => a.localeCompare(b))

const images = zen
  .filter((model) => model.type === "image")
  .flatMap((model) => {
    const path = new URL(model.api?.images?.base_url ?? "https://opencode.ai").pathname.replace(/^\/inference/, "")
    return path in imageAPIs ? [[model.id, imageAPIs[path as keyof typeof imageAPIs]] as const] : []
  })

const entries = (rows: ReadonlyArray<readonly [string, string]>) =>
  [...rows]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([id, value]) => `  ${JSON.stringify(id)}: ${JSON.stringify(value)},`)

await Bun.write(
  fileURLToPath(new URL("../src/models.ts", import.meta.url)),
  [
    "// Generated by script/models.ts from OpenCode's model lists. Do not edit by hand.",
    "export const models = {",
    ...entries(chat.map(([id, protocol]) => [id, protocol] as const)),
    "} as const",
    "",
    "export const outputLimits: Partial<Record<string, number>> = {",
    ...chat.flatMap(([id, protocol, output]) =>
      protocol === "messages" && output !== undefined ? [`  ${JSON.stringify(id)}: ${output},`] : [],
    ),
    "}",
    "",
    "export const imageModels = {",
    ...entries(images),
    "} as const",
    "",
  ].join("\n"),
)
console.log(`wrote ${chat.length} models and ${images.length} image models`)
