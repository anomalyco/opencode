#!/usr/bin/env bun

import { fileURLToPath } from "node:url"

// Regenerates src/models.ts from OpenCode's public model lists: each chat model's ID and the protocol it's served
// in natively. Run before a release so new models skip the name guess in src/protocol.ts.
const protocols = {
  messages: "messages",
  responses: "responses",
  "generate-content": "google",
  "chat-completions": "chat",
} as const

type Listed = { id: string; type: string; api?: Record<string, unknown>; recommended_api?: string }

const list = (path: string, prefix: string) =>
  fetch(`https://opencode.ai/inference${path}`)
    .then((response) => response.json() as Promise<{ data: Listed[] }>)
    .then((body) =>
      body.data
        .filter((model) => model.type === "chat" && model.api !== undefined)
        .flatMap((model) => {
          const api = Object.keys(model.api ?? {})
          const key =
            model.recommended_api !== undefined && model.recommended_api in protocols
              ? model.recommended_api
              : Object.keys(protocols).find((name) => api.includes(name))
          return key === undefined ? [] : [[prefix + model.id, protocols[key as keyof typeof protocols]] as const]
        }),
    )

const models = [...(await list("/v1/models", "")), ...(await list("/go/v1/models", "opencode-go/"))].sort(([a], [b]) =>
  a.localeCompare(b),
)

await Bun.write(
  fileURLToPath(new URL("../src/models.ts", import.meta.url)),
  [
    "// Generated by script/models.ts from OpenCode's model lists. Do not edit by hand.",
    "export const models = {",
    ...models.map(([id, protocol]) => `  ${JSON.stringify(id)}: ${JSON.stringify(protocol)},`),
    "} as const",
    "",
  ].join("\n"),
)
console.log(`wrote ${models.length} models`)
