export interface TablerIconProps extends ComponentProps<"svg"> {
  name: keyof typeof icons
  size?: number | string
}

export function TablerIcon(props: TablerIconProps) {
  const [local, rest] = splitProps(props, ["name", "size", "width", "height"])
  return (
    <Dynamic
      component={icons[local.name]}
      size={local.size ?? local.width ?? local.height ?? 20}
      stroke="1.75"
      aria-hidden="true"
      {...rest}
      data-icon-source="tabler"
      data-icon-role={local.name}
    />
  )
}
