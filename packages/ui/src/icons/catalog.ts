/** Icon names derived from the shared artwork, with no UI or runtime dependencies. */
export type IconName = keyof typeof icons | keyof typeof aliases

/** Every accepted icon name, aliases included, in sprite order. */
export function iconNames() {
  // SAFETY: every key comes from one of the two records that define IconName.
  return [...Object.keys(icons), ...Object.keys(aliases)] as IconName[]
}

/**
 * Narrows a name against the shared artwork catalog.
 * @param name - A name supplied by a caller, including names unknown to this build.
 */
export function isIconName(name: string): name is IconName {
  return Object.hasOwn(icons, name) || Object.hasOwn(aliases, name)
}

/**
 * The name whose artwork an icon draws: itself, or the name an alias points at.
 * @param name - A name validated by the type or by `isIconName`.
 */
export function resolveIconName(name: IconName) {
  // SAFETY: IconName is the union of both records' keys; a name that is not an alias is an icon.
  return Object.hasOwn(aliases, name) ? aliases[name as keyof typeof aliases] : (name as keyof typeof icons)
}

/**
 * The SVG body and viewport for a known catalog name.
 * @param name - A name validated by the type or by `isIconName`.
 */
export function getIcon(name: IconName) {
  return icons[resolveIconName(name)]
}

/** The names that have their own artwork, without aliases, in sprite order. */
export function artworkNames() {
  // SAFETY: the keys of icons are exactly its artwork names.
  return Object.keys(icons) as (keyof typeof icons)[]
}
