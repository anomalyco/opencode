export type DesktopMod = {
  id: string
  name: string
  version: string
  description?: string
  permissions: (
    | "storage"
    | "external.open"
    | "ui.sidebar"
    | "ui.command"
    | "ui.style"
    | "ui.host"
    | "server.host"
    | "server.database"
  )[]
  priority: number
  enabled: boolean
  compatible: boolean
  error?: string
  contributes?: {
    sidebar?: { id: string; title: string; entry: string; order?: number }[]
    commands?: { id: string; title: string; description?: string; panel?: string }[]
    styles?: string
    host?: string
    server?: string
    database?: { source: "production" }
  }
}

