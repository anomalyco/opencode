// Writes crates/util/fixtures/time.tsv: what the TypeScript client's `Date` and `Intl` calls give under Bun, in four
// time zones, for the known-answer tests of opencode-util's `time` module. Each zone runs in a child process with `TZ`
// set, as the client reads it. A `zone` line starts each zone's rows, `kind input output...`, tab-separated:
//
// - `at ms`: `toLocaleString()` (session list and export), `toDateString()` (session list, free limit),
//   `toLocaleDateString()` and `toLocaleTimeString(undefined, { timeStyle: "short" })` (`Locale.datetime`,
//   `Locale.time`), `formatReset`'s time and day (usage-limits.ts), `getHours()`, `getMinutes()`, `getDay()`, and the
//   local day number activity-calendar.ts takes; `invalid` for an Invalid Date.
// - `iso ms`: `toISOString()`, or `invalid` where it throws.
// - `days n`: the UTC year, month, day and weekday of `n * 86_400_000`.
// - `wall y m d h min`: `new Date(y, m - 1, d, h, min).getTime()`, as stats takes local midnights.
// - `parse text`: `Date.parse(text)` (`refusalReset`, the date-time form check), `NaN` if rejected, and the date form
//   check `validDate` (1 or 0).
const zones = ["UTC", "America/New_York", "Australia/Lord_Howe", "Asia/Kathmandu"]

if (process.argv[2] === "--zone") {
  process.stdout.write(rows(process.argv[3]).join("\n") + "\n")
  process.exit(0)
}

const file = new URL("../../crates/util/fixtures/time.tsv", import.meta.url).pathname
const lines = ["# Generated by script/gen/time.ts under Bun " + Bun.version + ". Do not edit."]
for (const zone of zones) {
  const proc = Bun.spawnSync(["bun", "run", import.meta.path, "--zone", zone], {
    env: { ...process.env, TZ: zone },
    stderr: "inherit",
  })
  if (proc.exitCode !== 0) process.exit(proc.exitCode ?? 1)
  lines.push(`zone\t${zone}`, proc.stdout.toString().trimEnd())
}
await Bun.write(file, lines.join("\n") + "\n")
console.log(`time: ${lines.join("\n").split("\n").length - 1} lines`)

function rows(zone: string) {
  const out: string[] = []
  const row = (...fields: (string | number)[]) => out.push(fields.join("\t"))

  const day = 86_400_000
  const transitions = [
    ...changes(Date.UTC(1985, 6, 1), Date.UTC(1986, 6, 1)),
    ...changes(Date.UTC(1995, 0, 1), Date.UTC(2030, 0, 1)),
  ]
  const instants = new Set<number>([
    ...range(Date.UTC(1900, 0, 1), Date.UTC(2100, 0, 1), 151 * day + 3_600_123),
    ...range(Date.UTC(2025, 0, 1), Date.UTC(2026, 0, 1), day + 7 * 3_600_000 + 61_007),
    ...transitions.flatMap((at) => [at - 1, at, at + 1_800_000]),
    ...[0, -1, 1, 999, -999, -1000, -1001, 1_762_268_645_123],
    ...[253_402_300_799_999, 253_402_300_800_000, -62_167_219_200_000, -62_167_219_200_001, -62_198_755_200_000],
    ...[8.64e15, -8.64e15, 8.64e15 + 1, -8.64e15 - 1],
  ])
  for (const ms of [...instants].sort((a, b) => a - b)) {
    const date = new Date(ms)
    if (Number.isNaN(date.getTime())) {
      row("at", ms, "invalid")
      continue
    }
    row(
      "at",
      ms,
      date.toLocaleString(),
      date.toDateString(),
      date.toLocaleDateString(),
      date.toLocaleTimeString(undefined, { timeStyle: "short" }),
      date.toLocaleTimeString("en-US", { hour: "numeric", minute: "2-digit" }).replace(/\u202f/g, " "),
      date.toLocaleDateString("en-US", { month: "short", day: "numeric" }),
      date.getHours(),
      date.getMinutes(),
      date.getDay(),
      Date.UTC(date.getFullYear(), date.getMonth(), date.getDate()) / day,
    )
  }

  if (zone === "UTC") {
    for (const ms of instants) {
      const date = new Date(ms)
      row("iso", ms, Number.isNaN(date.getTime()) ? "invalid" : date.toISOString())
    }
    for (const n of [...range(-100_000_000, 100_000_001, 199_999), -1, 0, 1, 59, 60, 11_016, -719_468, -719_469]) {
      const date = new Date(n * day)
      row("days", n, date.getUTCFullYear(), date.getUTCMonth() + 1, date.getUTCDate(), date.getUTCDay())
    }
  }

  // Local midnights: each January 1, each first of a month, each day with a transition and the day after. Every
  // quarter hour of the transition days of 2025 and of 1986 (Kathmandu's 15-minute gap).
  const walls = new Set<string>()
  for (let year = 1900; year <= 2100; year++) walls.add(`${year}\t1\t1\t0\t0`)
  for (let year = 1990; year <= 2030; year++)
    for (let month = 2; month <= 12; month++) walls.add(`${year}\t${month}\t1\t0\t0`)
  for (const at of transitions) {
    for (const shift of [-day, 0, day]) {
      const date = new Date(at + shift)
      const [year, month, dom] = [date.getFullYear(), date.getMonth() + 1, date.getDate()]
      walls.add(`${year}\t${month}\t${dom}\t0\t0`)
      if (shift !== 0 || (year !== 2025 && zone !== "Asia/Kathmandu")) continue
      for (let quarter = 0; quarter < 96; quarter++)
        walls.add(`${year}\t${month}\t${dom}\t${Math.floor(quarter / 4)}\t${(quarter % 4) * 15}`)
    }
  }
  for (const wall of walls) {
    const [year, month, dom, hour, minute] = wall.split("\t").map(Number)
    row("wall", wall, new Date(year, month - 1, dom, hour, minute).getTime())
  }

  for (const text of texts()) {
    const at = Date.parse(text)
    row("parse", JSON.stringify(text), Number.isNaN(at) ? "NaN" : at, validDate(text) ? 1 : 0)
  }
  return out
}

// The first instant of each change of offset between `from` and `to`.
function changes(from: number, to: number) {
  const offset = (ms: number) => new Date(ms).getTimezoneOffset()
  const found: number[] = []
  for (let at = from; at < to; at += 3_600_000) {
    if (offset(at) === offset(at + 3_600_000)) continue
    let [low, high] = [at, at + 3_600_000]
    while (high - low > 1) {
      const middle = Math.floor((low + high) / 2)
      if (offset(middle) === offset(low)) low = middle
      else high = middle
    }
    found.push(high)
  }
  return found
}

function range(from: number, to: number, step: number) {
  return Array.from({ length: Math.ceil((to - from) / step) }, (_, index) => from + index * step)
}

// packages/tui/src/util/form.ts
function validDate(value: string) {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(value)) return false
  const date = new Date(`${value}T00:00:00.000Z`)
  return !Number.isNaN(date.getTime()) && date.toISOString().slice(0, 10) === value
}

