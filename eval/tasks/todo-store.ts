const storeSolution = [
  'import type { Todo } from "./types"',
  "",
  "export type TodoStore = {",
  "  add: (title: string) => Todo",
  "  toggle: (id: number) => Todo",
  "  list: () => Todo[]",
  "}",
  "",
  "export function createStore(): TodoStore {",
  "  const todos: Todo[] = []",
  "  let nextID = 1",
  "  return {",
  "    add(title) {",
  "      const todo = { id: nextID++, title, done: false }",
  "      todos.push(todo)",
  "      return { ...todo }",
  "    },",
  "    toggle(id) {",
  "      const todo = todos.find((item) => item.id === id)",
  '      if (todo === undefined) throw new Error("todo not found: " + id)',
  "      todo.done = !todo.done",
  "      return { ...todo }",
  "    },",
  "    list() {",
  "      return todos.map((todo) => ({ ...todo }))",
  "    },",
  "  }",
  "}",
  "",
].join("\n")

