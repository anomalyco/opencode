        # Russian dictionary, so the Belarusian bundle stays in parity.
        en_rel = src_rel.replace("ru.ts", "en.ts")
        en_path = os.path.join(base, en_rel)
        if os.path.exists(en_path):
            en_dict = dict(parse_ts(en_path))
            have = {k for k, _ in translated}
            for k, v in en_dict.items():
                if k not in have:
                    translated.append((k, KEY_OVERRIDES.get(k, EN_OVERRIDES.get(k, v))))

        # Apply orthography fixes to every value (including LLM / reviewer
        # overrides): у/ў after vowels, never start with "Ў", plus typo fixes.
        translated = [(k, apply_post_fixes(fix_u_short(t))) for k, t in translated]

        write_ts(dst, translated)


