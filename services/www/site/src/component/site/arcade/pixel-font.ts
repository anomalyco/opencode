/** Each glyph is 5 cells wide with 1 cell between glyphs, and 7 cells tall. */
export const pixelWidth = (text: string) => text.length * 6 - 1

/** The lit cells of `text`, as [x, y] in cell units. */
export function pixelCells(text: string) {
  return [...text.toUpperCase()].flatMap((char, index) =>
    (glyphs[char] ?? glyphs[" "])
      .split(" ")
      .flatMap((row, y) => [...row].flatMap((bit, x) => (bit === "1" ? [[index * 6 + x, y] as const] : []))),
  )
}

/** Draw `text` into a 2D canvas with its top-left at (x, y), each cell `cell` px square. */
export function drawPixelText(ctx: CanvasRenderingContext2D, text: string, x: number, y: number, cell: number) {
  for (const [cx, cy] of pixelCells(text)) ctx.fillRect(x + cx * cell, y + cy * cell, cell, cell)
}
